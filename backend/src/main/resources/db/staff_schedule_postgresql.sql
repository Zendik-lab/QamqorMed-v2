ALTER TABLE nurse_profiles ADD COLUMN IF NOT EXISTS about varchar(4000);

ALTER TABLE doctor_nurse_assignments ADD COLUMN IF NOT EXISTS unassigned_at timestamptz;

CREATE TABLE IF NOT EXISTS doctor_schedules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id bigint NOT NULL UNIQUE REFERENCES doctor_profiles(id),
    slot_duration_minutes integer NOT NULL DEFAULT 30,
    time_zone varchar(60) NOT NULL DEFAULT 'Asia/Almaty',
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS doctor_schedule_intervals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id bigint NOT NULL REFERENCES doctor_schedules(id) ON DELETE CASCADE,
    day_of_week varchar(12) NOT NULL,
    start_time time NOT NULL,
    end_time time NOT NULL,
    is_break boolean NOT NULL DEFAULT false,
    CONSTRAINT ck_schedule_interval_order CHECK (end_time > start_time)
);

CREATE TABLE IF NOT EXISTS schedule_exceptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id bigint NOT NULL REFERENCES doctor_schedules(id) ON DELETE CASCADE,
    exception_date date NOT NULL,
    type varchar(32) NOT NULL,
    start_time time,
    end_time time,
    note varchar(300),
    CONSTRAINT uk_schedule_exception_date UNIQUE (schedule_id, exception_date),
    CONSTRAINT ck_schedule_exception_order CHECK (end_time IS NULL OR start_time IS NOT NULL AND end_time > start_time)
);

CREATE INDEX IF NOT EXISTS idx_schedule_intervals_schedule_day ON doctor_schedule_intervals(schedule_id, day_of_week);
CREATE INDEX IF NOT EXISTS idx_schedule_exceptions_date ON schedule_exceptions(exception_date);
CREATE UNIQUE INDEX IF NOT EXISTS uk_appointments_doctor_active_time ON appointments(doctor_profile_id, appointment_at) WHERE status <> 'CANCELLED';
